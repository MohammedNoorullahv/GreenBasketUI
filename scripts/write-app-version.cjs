'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const version = pkg.version;
if (typeof version !== 'string' || !/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/.test(version) || version.length > 50) {
  throw new Error('package.json must contain a valid version of at most 50 characters, e.g. 0.1.0.');
}
let commit = '';
try { commit = execFileSync('git', ['rev-parse', '--short=7', 'HEAD'], { cwd: root, encoding: 'utf8', stdio: ['ignore','pipe','ignore'] }).trim(); }
catch { /* Git metadata is optional, for example in an exported source directory. */ }
const metadata = { version, builtAtUtc: new Date().toISOString(), commit };
const file = path.join(root, 'src', 'app', 'shared', 'app-version.ts');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, '// Generated by scripts/write-app-version.cjs. Do not edit manually.\nexport const APP_VERSION = ' + JSON.stringify(metadata, null, 2) + ' as const;\n', 'utf8');
console.log('App version prepared: ' + version);
