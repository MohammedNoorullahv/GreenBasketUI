@Pipe({ name: 'menuCaption', standalone: true, pure: false })
export class MenuCaptionPipe implements PipeTransform {
  private readonly translate = inject(TranslateService);
  private readonly cache = new Map<string, {
    exact: Map<string, string>;
    patterns: { key: string; pattern: RegExp; parameters: string[] }[];
  }>();

  transform(value: unknown, section: string): string {
    if (value == null) return '';
    const original = String(value);
    const text = original.replace(/\s+/g, ' ').trim();
    let menu = this.cache.get(section);
    if (!menu) {
      menu = { exact: new Map(), patterns: [] };
      for (const [english, key] of Object.entries(CAPTIONS[section] || {})) {
        menu.exact.set(english.toLowerCase(), key);
        const parameters: string[] = [];
        let cursor = 0, pattern = '^';
        const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        for (const match of english.matchAll(/\{\{(p\d+)\}\}/g)) {
          pattern += escape(english.slice(cursor, match.index)) + '(.+?)';
          parameters.push(match[1]);
          cursor = (match.index || 0) + match[0].length;
        }
        if (parameters.length) {
          pattern += escape(english.slice(cursor)) + '$';
          menu.patterns.push({ key, pattern: new RegExp(pattern, 'i'), parameters });
        }
      }
      this.cache.set(section, menu);
    }
    const exactKey = menu.exact.get(text.toLowerCase());
    if (exactKey) return this.caption(section, exactKey, {}, original);
    for (const entry of menu.patterns) {
      const match = entry.pattern.exec(text);
      if (!match) continue;
      const params: Record<string, string> = {};
      entry.parameters.forEach((name, index) => {
        const captured = match[index + 1];
        const nestedKey = menu!.exact.get(captured.toLowerCase());
        params[name] = nestedKey ? this.caption(section, nestedKey, {}, captured) : captured;
      });
      return this.caption(section, entry.key, params, original);
    }
    // Unknown API messages or user-entered content stay intact.
    return original;
  }

  private caption(section: string, key: string, params: Record<string, string>, fallback: string): string {
    const fullKey = `${section}.${key}`;
    const result = this.translate.instant(fullKey, params);
    return typeof result === 'string' && result !== fullKey ? result : fallback;
  }
}
